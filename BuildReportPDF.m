function f = findFig(figRoot, tag, ch, typeToken)
    d = dir(fullfile(figRoot, char(tag), char(ch) + "_*" + char(typeToken) + "*.png"));
    if isempty(d), f = ""; else, f = string(fullfile(d(1).folder, d(1).name)); end
end

function s = prettyType(tt)
    m = struct("baseline_comparison","Baseline comparison", ...
               "x16_strategies","16-strategy raster", ...
               "strategy_agreement_Jaccard","Strategy agreement (Jaccard)", ...
               "consensus","Consensus", ...
               "smoothing_comparison","Smoothing comparison", ...
               "anomaly_classification","Anomaly classification");
    key = matlab.lang.makeValidName(tt);
    if isfield(m, key), s = string(m.(key)); else, s = tt; end
end

function out = wrapText(str, width)
%WRAPTEXT Word-wrap to `width` chars, honouring explicit newlines in the input.
    % Coerce to a single scalar string first: readme bodies may arrive as a
    % char row vector or a multi-piece string, either of which breaks splitlines.
    if isstring(str) && ~isscalar(str)
        str = strjoin(str, " ");
    end
    str = string(join(string(cellstr(str)), newline));  % char matrix rows -> newline-joined
    paras = splitlines(str);   % keep paragraph breaks from newline chars
    allLines = strings(0);
    for pi = 1:numel(paras)
        words = split(strtrim(paras(pi)));
        if numel(words) == 1 && words(1) == ""
            allLines(end+1) = ""; %#ok<AGROW>
            continue;
        end
        line = "";
        for wi = 1:numel(words)
            wr = words(wi);
            if strlength(line) == 0
                line = wr;
            elseif strlength(line) + strlength(wr) + 1 > width
                allLines(end+1) = line; line = wr; %#ok<AGROW>
            else
                line = line + " " + wr;
            end
        end
        if strlength(line) > 0, allLines(end+1) = line; end %#ok<AGROW>
    end
    out = char(strjoin(allLines, newline));
end

