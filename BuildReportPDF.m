function buildWithReportGen(outPdf, baseDir, figRoot, runTags, runDesc, channels, figBlurb, readme) %#ok<INUSD>
import mlreportgen.dom.*;
d = Document(char(erase(outPdf, ".pdf")), "pdf");
open(d);

% Title + README/methods.
append(d, makeTitle("EPR Imaging - Anomaly-Detection Method Report"));
for i = 1:size(readme, 1)
    h = Heading2(char(readme{i, 1})); append(d, h);
    p = Paragraph(char(readme{i, 2})); p.Style = {FontSize("10pt")}; append(d, p);
end
append(d, PageBreak());

% Figures: run -> channel -> figure type.
typeOrder = ["baseline_comparison", "16_strategies", "strategy_agreement_Jaccard", ...
             "consensus", "smoothing_comparison", "anomaly_classification"];
for r = 1:numel(runTags)
    tag = runTags(r);
    h = Heading1(sprintf("Run: %s", tag)); append(d, h);
    pr = Paragraph(char(runDesc.(tag))); pr.Style = {FontSize("10pt"), Italic(true)}; append(d, pr);
    for c = 1:numel(channels)
        ch = channels(c);
        for tt = typeOrder
            f = findFig(figRoot, tag, ch, tt);
            if f == "", continue; end
            hh = Heading3(sprintf("%s - %s", ch, prettyType(tt))); append(d, hh);
            blurb = Paragraph(char(figBlurb.(matlab.lang.makeValidName(tt)))); blurb.Style = {FontSize("9pt")};
            append(d, blurb);
            img = Image(char(f)); img.Style = {ScaleToFit(true)}; append(d, img);
            append(d, PageBreak());
        end
    end
end
close(d);
end


%% ======================================================================
function buildWithPrint(outPdf, figRoot, runTags, runDesc, channels, figBlurb, combBlurb, readme)
% Fallback: no Report Generator. Render each page as a figure (text or image)
% and append to a multipage PDF with exportgraphics('Append').
    typeOrder = ["baseline_comparison", "16_strategies", "strategy_agreement_Jaccard", ...
                 "consensus", "smoothing_comparison", "anomaly_classification"];

    % --- README/methods text pages ---
    printTextPage(outPdf, "EPR Imaging - Anomaly-Detection Method Report", readme, true);
    % --- figures ---
    for r = 1:numel(runTags)
        tag = runTags(r);
        printSectionPage(outPdf, sprintf("RUN: %s", upper(tag)), runDesc.(tag));
        for c = 1:numel(channels)
            for tt = typeOrder
                f = findFig(figRoot, tag, channels(c), tt);
                if f == "", continue; end
                printImagePage(outPdf, ...
                    sprintf("%s  |  %s - %s", upper(tag), channels(c), prettyType(tt)), ...
                    figBlurb.(matlab.lang.makeValidName(tt)), f);
            end
        end
        % --- Combined cross-channel figures for this run ---
        combFiles = dir(fullfile(figRoot, char(tag), "PAIR_*.png"));
        combFiles = [combFiles;
                     dir(fullfile(figRoot, char(tag), "CONCURRENT_*.png"))];
        for cf = 1:numel(combFiles)
            fpath = string(fullfile(combFiles(cf).folder, combFiles(cf).name));
            nm = string(combFiles(cf).name);
            if startsWith(nm, "PAIR")
                blurb = combBlurb.PAIR;
                pageTitle = sprintf("%s  |  Combined - %s", upper(tag), erase(nm, ".png"));
            elseif contains(nm, "top_windows")
                blurb = combBlurb.CONCURRENT_anomalies_top_windows;
                pageTitle = sprintf("%s  |  Combined - Top concurrent-anomaly windows", upper(tag));
            else
                blurb = combBlurb.CONCURRENT_anomalies_cross_channel;
                pageTitle = sprintf("%s  |  Combined - Cross-channel concurrent anomalies", upper(tag));
            end
            printImagePage(outPdf, pageTitle, blurb, fpath);
        end
    end
end

function printTextPage(outPdf, titleStr, readme, isFirst)
%PRINTTEXTPAGE Flow the README onto pages using ONE multi-line text object per
% page (MATLAB handles line spacing), page-broken by a fixed line budget.  This
% avoids the per-line cursor overlap of manual positioning.  Headings are
% rendered with a leading ">>" and blank-line padding for visual separation.
    bodyW       = 105;    % wrap width (chars)
    linesPerPg  = 52;     % monospace lines that fit one portrait page at 8pt

    % Build one flat cellstr of lines (headings marked, bodies wrapped).  Every
    % readme cell is coerced to a scalar string first (they may arrive as char
    % row vectors or multi-piece strings, which would break scalar assignment).
    scalarStr = @(x) string(join(string(cellstr(x)), " "));
    all = strings(1,0);
    all(end+1) = ">>> " + scalarStr(titleStr);
    all(end+1) = "";
    for i = 1:size(readme,1)
        all(end+1) = ">> " + scalarStr(readme{i,1});            %#ok<AGROW> heading
        bl = splitlines(string(wrapText(readme{i,2}, bodyW)));
        all = [all, reshape(bl, 1, [])];                        %#ok<AGROW>
        all(end+1) = "";                                        %#ok<AGROW> spacer
    end

    % Emit in page-sized chunks, each as a single left-aligned monospace block.
    n = numel(all);
    for s = 1:linesPerPg:n
        e = min(s + linesPerPg - 1, n);
        block = strjoin(all(s:e), newline);
        fig = figure("Visible","off","Units","inches","Position",[0 0 8.5 11], ...
                 "Color","w","PaperUnits","inches","PaperSize",[8.5 11], ...
                 "PaperPosition",[0 0 8.5 11]);
        ax = axes(fig,"Position",[0.06 0.03 0.90 0.94]); axis(ax,"off"); %#ok<LAXES>
        ylim(ax,[0 1]); xlim(ax,[0 1]);
        text(ax, 0, 1, block, "FontName","FixedWidth", "FontSize", 8, ...
             "VerticalAlignment","top", "Interpreter","none");
        appendPage(fig, outPdf, isFirst); isFirst = false; close(fig);
    end
end

function printSectionPage(outPdf, titleStr, desc)
    fig = figure("Visible","off","Units","inches","Position",[0 0 8.5 11],"Color","w", ...
                 "PaperUnits","inches","PaperSize",[8.5 11],"PaperPosition",[0 0 8.5 11]);
    ax = axes(fig,"Position",[0.08 0 0.84 1]); axis(ax,"off"); ylim(ax,[0 1]); xlim(ax,[0 1]);
    text(ax,0,0.62,titleStr,"FontSize",22,"FontWeight","bold","Interpreter","none");
    text(ax,0,0.52,wrapText(desc,90),"FontSize",11,"VerticalAlignment","top","Interpreter","none");
    appendPage(fig, outPdf, false); close(fig);
end

function printImagePage(outPdf, titleStr, blurb, imgPath)
    % LANDSCAPE letter page (11 x 8.5) so the wide figures sit UPRIGHT at full
    % size - no head-tilting, maximum readability.  Title across the top, figure
    % filling the middle band at its native aspect, blurb along the bottom.
    fig = figure("Visible","off","Units","inches","Position",[0 0 11 8.5],"Color","w", ...
                 "PaperUnits","inches","PaperSize",[11 8.5],"PaperPosition",[0 0 11 8.5]);
    % Title (top)
    annotation(fig,"textbox",[0.03 0.955 0.94 0.04],"String",titleStr,"EdgeColor","none", ...
        "FontSize",13,"FontWeight","bold","Interpreter","none","VerticalAlignment","top");

    im = imread(char(imgPath));
    [ih, iw, ~] = size(im);

    % Image band between title and caption; fit preserving aspect, centred.
    bandY0 = 0.135;  bandY1 = 0.945;
    bandX0 = 0.02;   bandX1 = 0.98;
    bandW = bandX1-bandX0; bandH = bandY1-bandY0;
    pageAR = 11/8.5;                     % page width/height (normalized units use this)
    imgAR  = iw/ih;
    fitW = bandW; fitH = fitW * (1/imgAR) * pageAR;
    if fitH > bandH, fitH = bandH; fitW = fitH * imgAR / pageAR; end
    axX = bandX0 + (bandW - fitW)/2;
    axY = bandY0 + (bandH - fitH)/2;
    ax = axes(fig,"Position",[axX axY fitW fitH]);
    imshow(im,"Parent",ax,"Border","tight");

    % Blurb (bottom, full width)
    annotation(fig,"textbox",[0.03 0.015 0.94 0.105], ...
        "String",wrapText(blurb,155),"EdgeColor",[0.7 0.7 0.7], ...
        "FontSize",9.5,"Interpreter","none","VerticalAlignment","top", ...
        "BackgroundColor",[0.97 0.97 0.97]);
    appendPage(fig, outPdf, false); close(fig);
end

function appendPage(fig, outPdf, isFirst)
    % Export at high resolution so the embedded raster figures stay crisp.
    if isFirst
        exportgraphics(fig, outPdf, "ContentType","image", "Resolution", 220);
    else
        exportgraphics(fig, outPdf, "ContentType","image", "Resolution", 220, "Append", true);
    end
end


